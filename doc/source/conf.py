"""Sphinx configuration for the xsf documentation.

The C++ API reference is generated by Doxygen and rendered through Breathe.
"""

import tomllib
import xml.etree.ElementTree as ET
from datetime import datetime
from pathlib import Path

DOC_DIR = Path(__file__).resolve().parents[1]
REPO_DIR = DOC_DIR.parent

# -- Project information -----------------------------------------------------

project = "xsf"
author = "the xsf developers"
copyright = f"{datetime.now().year}, {author}"

with open(REPO_DIR / "pixi.toml", "rb") as f:
    release = tomllib.load(f)["workspace"]["version"]
version = ".".join(release.split(".")[:2])

# -- General configuration ---------------------------------------------------

extensions = [
    "sphinx.ext.mathjax",
    "breathe",
]

exclude_patterns = ["_build", "Thumbs.db", ".DS_Store"]
root_doc = "index"

# -- Options for HTML output -------------------------------------------------

html_theme = "pydata_sphinx_theme"
html_title = f"{project} v{release}"

html_theme_options = {
    "show_nav_level": 1,
    "navigation_depth": 4,
    "collapse_navigation": False,
    "github_url": "https://github.com/scipy/xsf",
}

# -- Breathe configuration ---------------------------------------------------

DOXYGEN_XML = DOC_DIR / "_build" / "doxygen" / "xml"

breathe_projects = {"xsf": str(DOXYGEN_XML)}
breathe_default_project = "xsf"
breathe_domain_by_extension = {"h": "cpp"}

# Each API page declares the ``xsf`` namespace that contains its functions,
# which Sphinx reports as a duplicate declaration.
suppress_warnings = ["duplicate_declaration.cpp"]

# -- API reference pages -----------------------------------------------------

# Headers that declare xsf functions but are not part of the kernel API.
API_EXCLUDED_HEADERS = {
    "xsf/config.h",
    "xsf/cpu/amos.h",
    "xsf/cupy.h",
    "xsf/fp_error_metrics.h",
}


def write_api_pages():
    """Write one API page per header that declares public xsf functions.

    The headers are found from the Doxygen XML, so the pages track the
    headers without manual bookkeeping. The pages are written to
    ``api/generated`` (``api/generated/cpu`` for the CPU-only headers),
    which is ignored by Git.
    """
    headers = set()
    for path in DOXYGEN_XML.glob("namespacexsf*.xml"):
        compound = ET.parse(path).getroot().find("compounddef")
        for member in compound.iter("memberdef"):
            if member.get("kind") == "function":
                headers.add(member.find("location").get("file"))

    out_dir = DOC_DIR / "source" / "api" / "generated"
    pages = {}
    for header in sorted(headers - API_EXCLUDED_HEADERS):
        title = f"``{header}``"
        page = Path(header).relative_to("xsf").with_suffix(".rst")
        pages[out_dir / page] = (
            f"{title}\n{'=' * len(title)}\n\n"
            f".. code-block:: cpp\n\n   #include <{header}>\n\n"
            f".. doxygenfile:: {header}\n   :project: xsf\n"
        )

    for stale in set(out_dir.rglob("*.rst")) - set(pages):
        stale.unlink()
    for page, text in pages.items():
        page.parent.mkdir(parents=True, exist_ok=True)
        # Only rewrite changed pages so that Sphinx rebuilds incrementally.
        if not page.exists() or page.read_text() != text:
            page.write_text(text)


write_api_pages()
